-- CineScope: estrutura inicial do banco Supabase
-- Execute no SQL Editor do seu projeto Supabase.

create table if not exists public.perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome_completo text not null default '',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.favoritos (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  filme_id bigint not null,
  created_at timestamptz not null default now(),
  unique (usuario_id, filme_id)
);

create table if not exists public.comentarios (
  id bigint generated by default as identity primary key,
  filme_id bigint not null,
  usuario text not null,
  texto text not null,
  created_at timestamptz not null default now()
);

-- Cria automaticamente o perfil quando uma conta é cadastrada.
create or replace function public.criar_perfil_usuario()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.perfis (id, nome_completo)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'nome_completo', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists ao_criar_usuario on auth.users;
create trigger ao_criar_usuario after insert on auth.users
for each row execute procedure public.criar_perfil_usuario();

-- Ativa RLS.
alter table public.perfis enable row level security;
alter table public.favoritos enable row level security;
alter table public.comentarios enable row level security;

-- Cada usuário só acessa/edita seu próprio perfil.
drop policy if exists "Perfil visível pelo próprio usuário" on public.perfis;
create policy "Perfil visível pelo próprio usuário" on public.perfis
for select to authenticated using (auth.uid() = id);
drop policy if exists "Usuário cria seu perfil" on public.perfis;
create policy "Usuário cria seu perfil" on public.perfis
for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Usuário atualiza seu perfil" on public.perfis;
create policy "Usuário atualiza seu perfil" on public.perfis
for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- Favoritos privados por usuário.
drop policy if exists "Usuário vê seus favoritos" on public.favoritos;
create policy "Usuário vê seus favoritos" on public.favoritos
for select to authenticated using (auth.uid() = usuario_id);
drop policy if exists "Usuário adiciona seus favoritos" on public.favoritos;
create policy "Usuário adiciona seus favoritos" on public.favoritos
for insert to authenticated with check (auth.uid() = usuario_id);
drop policy if exists "Usuário remove seus favoritos" on public.favoritos;
create policy "Usuário remove seus favoritos" on public.favoritos
for delete to authenticated using (auth.uid() = usuario_id);

-- Comentários: leitura pública e envio público, conforme o formulário atual do site.
drop policy if exists "Comentários visíveis para todos" on public.comentarios;
create policy "Comentários visíveis para todos" on public.comentarios
for select to anon, authenticated using (true);
drop policy if exists "Visitantes podem comentar" on public.comentarios;
create policy "Visitantes podem comentar" on public.comentarios
for insert to anon, authenticated with check (length(trim(usuario)) > 0 and length(trim(texto)) > 0);

-- Permissões básicas para a API do Supabase.
grant select, insert, update on public.perfis to authenticated;
grant select, insert, delete on public.favoritos to authenticated;
grant select, insert on public.comentarios to anon, authenticated;


-- Bucket público para fotos de perfil.
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

drop policy if exists "Avatares públicos podem ser visualizados" on storage.objects;
create policy "Avatares públicos podem ser visualizados" on storage.objects
for select to public using (bucket_id = 'avatars');

drop policy if exists "Usuário envia seu próprio avatar" on storage.objects;
create policy "Usuário envia seu próprio avatar" on storage.objects
for insert to authenticated with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Usuário atualiza seu próprio avatar" on storage.objects;
create policy "Usuário atualiza seu próprio avatar" on storage.objects
for update to authenticated using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text)
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
